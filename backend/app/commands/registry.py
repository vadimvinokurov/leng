"""Command registry: the declarative list of API commands and their handlers.

Every rule 2 route is declared once here. `AppContext` is the single
bag of runtime dependencies a handler may close over; builders turn a
context into the concrete endpoint function. Routes are generated by
the generic loop in `app.api.routes.create_app`.

Per-command validations (empty_text / text_too_long, LLMError -> 502,
404 word_not_found) live inside the handlers below, exactly as before.
Builders signal them by raising `CommandError`, a neutral error the API
layer (app.api.routes) translates into HTTP — the registry itself stays
free of UI/server imports.
"""

import json
import logging
import sqlite3
from collections.abc import Callable
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from app import mirror
from app.config import Config
from app.db import connect
from app.llm.base import LLMClient, LLMError
from app.schemas import QueryIn
from app.service.query import Source, process_query
from app.service.state import snapshot

MAX_TEXT_LEN = 50_000

logger = logging.getLogger(__name__)

# Every handler serves either a JSON-serializable dict or a Response
# object (the downloads surface streams files and HTML); the concrete
# types vary per command (see each builder), hence Any.
Endpoint = Callable[..., Any]


class CommandError(Exception):
    """HTTP-facing error a builder raises; translated by the API layer."""

    def __init__(self, status_code: int, detail: dict[str, str]) -> None:
        super().__init__(status_code, detail)
        self.status_code = status_code
        self.detail = detail


@dataclass(frozen=True)
class AppContext:
    cfg: Config
    llm: LLMClient
    clock: Callable[[], datetime]
    # GitHub transport for the release mirror (injectable in tests; the
    # production default is mirror.HttpxTransport built on demand).
    mirror_transport: "mirror.Transport | None" = None


@dataclass(frozen=True)
class Command:
    id: str
    method: str
    path: str
    params: type[BaseModel] | None
    auth: bool
    builder: Callable[[AppContext], Endpoint]
    # How the API layer renders the builder's neutral return value:
    # "json" (dict), "html" (str body) or "file" (a path to stream).
    renders: str = "json"


def build_health(ctx: AppContext) -> Endpoint:
    cfg = ctx.cfg

    def health() -> dict[str, Any]:
        return {"status": "ok", "version": cfg.version}

    return health


def build_query(ctx: AppContext) -> Endpoint:
    cfg, llm, clock = ctx.cfg, ctx.llm, ctx.clock

    def query(body: QueryIn) -> dict[str, Any]:
        text = body.raw_text.strip()
        if not text:
            raise CommandError(status_code=400, detail={"error": "empty_text"})
        if len(body.raw_text) > MAX_TEXT_LEN:
            raise CommandError(
                status_code=400, detail={"error": "text_too_long"}
            )
        source = Source(
            app=body.source.app, title=body.source.title, url=body.source.url
        )
        # A per-request connection: sync handlers run on the threadpool,
        # so a shared connection would span threads (sqlite3 forbids
        # that); per-request keeps every use thread-confined.
        conn = connect(cfg.db_path)
        try:
            result = process_query(conn, llm, text, source, body.client, clock())
        except LLMError as exc:
            raise CommandError(
                status_code=502, detail={"error": "llm_error"}
            ) from exc
        finally:
            conn.close()
        return {
            "query_id": result.query_id,
            "kind": result.kind,
            "canonical": result.canonical,
            "response": result.response,
            "soft_mode": result.soft_mode,
        }

    return query


def build_word_history(ctx: AppContext) -> Endpoint:
    cfg = ctx.cfg

    def word_history(word_id: int) -> dict[str, Any]:
        """List the queries linked to a word entry, newest first.

        History items carry the translation parsed from the stored JSON
        string. A row whose stored translation does not parse is skipped
        (defensive: internal writes always store a JSON object, so this is
        unreachable through the API) — an unparsable row must not erase the
        rest of the history for the soft-HUD listing.
        """
        conn = connect(cfg.db_path)
        conn.row_factory = sqlite3.Row
        try:
            word = conn.execute(
                "SELECT canonical, occurrences FROM word_entries WHERE id = ?",
                (word_id,),
            ).fetchone()
            if word is None:
                raise CommandError(
                    status_code=404, detail={"error": "word_not_found"}
                )
            rows = conn.execute(
                """
                SELECT q.created_at, q.source_app, q.source_title,
                       q.source_url, q.raw_text, q.translation
                FROM query_word_links l
                JOIN queries q ON q.id = l.query_id
                WHERE l.word_id = ?
                ORDER BY q.created_at DESC
                """,
                (word_id,),
            ).fetchall()
        finally:
            conn.close()
        history = []
        for row in rows:
            try:
                translation = json.loads(row["translation"])
            except (ValueError, TypeError) as exc:
                logger.warning(
                    "word %s: skipping history row %s with unparsable "
                    "translation JSON: %s",
                    word_id,
                    row["created_at"],
                    exc,
                )
                continue
            history.append(
                {
                    "created_at": row["created_at"],
                    "source_app": row["source_app"],
                    "source_title": row["source_title"],
                    "source_url": row["source_url"],
                    "raw_text": row["raw_text"],
                    "translation": translation,
                }
            )
        return {
            "word_id": word_id,
            "canonical": word["canonical"],
            "occurrences": word["occurrences"],
            "history": history,
        }

    return word_history


def build_commands(ctx: AppContext) -> Endpoint:  # noqa: ARG001
    # Uniform builder signature: the dispatch always passes ctx.
    def commands() -> dict[str, Any]:
        """Describe every registry command for API clients to build on."""
        return {
            "commands": [
                {
                    "id": command.id,
                    "method": command.method,
                    "path": command.path,
                    "auth": command.auth,
                    "params_schema": (
                        command.params.model_json_schema()
                        if command.params is not None
                        else None
                    ),
                }
                for command in COMMANDS
            ]
        }

    return commands


def build_state(ctx: AppContext) -> Endpoint:
    cfg = ctx.cfg

    def state() -> dict[str, Any]:
        """Serve the full headless snapshot (rule 6) from a fresh connection."""
        conn = connect(cfg.db_path)
        try:
            return snapshot(conn)
        finally:
            conn.close()

    return state


class RefreshIn(BaseModel):
    """POST /v1/clients/refresh takes no parameters (empty body)."""


def _cached_files(cfg: Config) -> list[str]:
    """Names of mirror-cache files the page may link to."""
    clients = mirror.clients_dir(cfg)
    if not clients.is_dir():
        return []
    return sorted(
        entry.name
        for entry in clients.iterdir()
        if entry.is_file()
        and entry.name != mirror.MANIFEST_NAME
        and not entry.name.endswith(".sig")
    )


def _safe_cached_path(cfg: Config, name: str) -> Path | None:
    """Resolve a requested filename inside the cache, rejecting traversal.

    A name that is not a plain file name (contains separators, dots
    tricks) or that does not exist in the cache yields None.
    """
    if not name or "/" in name or "\\" in name:
        return None
    if Path(name).name != name or name in (".", ".."):
        return None
    path = mirror.clients_dir(cfg) / name
    if not path.is_file():
        return None
    return path


def _mirror_empty() -> CommandError:
    return CommandError(status_code=404, detail={"error": "mirror_empty"})


def build_downloads_page(ctx: AppContext) -> Endpoint:
    cfg = ctx.cfg

    def page() -> str:
        """Build the downloads page body; rendered as HTML by the API layer."""
        files = _cached_files(cfg)
        if files:
            rows = "".join(
                f'<li><a href="/v1/clients/files/{name}">{name}</a></li>'
                for name in files
            )
            return (
                f"<html><body><h1>Leng {cfg.version}</h1>"
                f"<ul>{rows}</ul></body></html>"
            )
        return (
            f"<html><body><h1>Leng {cfg.version}</h1>"
            f'<p>Downloads: <a href="https://github.com/{cfg.github_repo}'
            f'/releases">GitHub Releases</a></p></body></html>'
        )

    return page


def build_client_manifest(ctx: AppContext) -> Endpoint:
    cfg = ctx.cfg

    def manifest() -> dict[str, Any]:
        """Serve the cached updater manifest raw; the API layer rewrites
        each platform URL to point at this server."""
        path = mirror.clients_dir(cfg) / mirror.MANIFEST_NAME
        if not path.is_file():
            raise _mirror_empty()
        parsed: dict[str, Any] = json.loads(path.read_bytes())
        return parsed

    return manifest


def build_client_file(ctx: AppContext) -> Endpoint:
    cfg = ctx.cfg

    def client_file(name: str) -> Path:
        """Return the cached file to stream; the API layer makes a
        FileResponse out of the path."""
        path = _safe_cached_path(cfg, name)
        if path is None:
            raise _mirror_empty()
        return path

    return client_file


def build_client_refresh(ctx: AppContext) -> Endpoint:
    cfg = ctx.cfg
    injected_transport = ctx.mirror_transport

    def refresh(_: RefreshIn) -> dict[str, Any]:
        try:
            mirror.sync_mirror(cfg, injected_transport or mirror.HttpxTransport())
        except (mirror.MirrorError, mirror.TransportError) as exc:
            logger.warning("mirror refresh failed: %s", exc)
            raise CommandError(
                status_code=502, detail={"error": "mirror_unavailable"}
            ) from exc
        return {"status": "ok"}

    return refresh


